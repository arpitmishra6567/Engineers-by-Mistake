"""
Execution context and data transfer objects for the repair workflow.
"""

from __future__ import annotations

import time
import uuid
from pathlib import Path
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field

from repairforge.agent.state import AgentState, StateTransitionRecord


class BugReport(BaseModel):
    """Parsed bug report information."""
    title: str = Field(..., description="Bug summary/title")
    description: str = Field(default="", description="Detailed description")
    expected_behavior: str = Field(default="", description="Expected outcome")
    actual_behavior: str = Field(default="", description="Observed failing outcome")
    error_message: Optional[str] = Field(default=None, description="Exception or error message")
    stack_trace: Optional[str] = Field(default=None, description="Captured stack trace")
    reproduction_command: Optional[str] = Field(default=None, description="Specific test command")


class RepoSummary(BaseModel):
    """Repository analysis metadata."""
    root_path: Path = Field(..., description="Absolute path to repo root")
    total_files: int = Field(default=0)
    source_files: List[str] = Field(default_factory=list)
    languages: List[str] = Field(default_factory=list)
    has_git: bool = Field(default=False)
    has_tests: bool = Field(default=False)
    test_framework: Optional[str] = Field(default=None)
    dependency_files: List[str] = Field(default_factory=list)


class ReproductionResult(BaseModel):
    """Evidence from running the bug reproduction."""
    status: str = Field(..., description="'REPRODUCED', 'NOT_REPRODUCED', or 'BLOCKED'")
    command: str = Field(..., description="Executed command")
    exit_code: int = Field(..., description="Command exit code")
    stdout: str = Field(default="")
    stderr: str = Field(default="")
    duration_seconds: float = Field(default=0.0)
    evidence_notes: str = Field(default="")


class RootCauseRecord(BaseModel):
    """Root cause analysis findings."""
    file_path: str = Field(..., description="Primary affected file path")
    function_name: Optional[str] = Field(default=None, description="Affected function or class")
    line_number: Optional[int] = Field(default=None, description="Line number if known")
    explanation: str = Field(..., description="Technical explanation of the defect")
    uncertainty_level: str = Field(default="LOW", description="'LOW', 'MEDIUM', 'HIGH'")
    evidence: str = Field(..., description="Supporting test or trace evidence")


class PatchRecord(BaseModel):
    """Generated code patch."""
    file_path: str = Field(..., description="Path to file being patched")
    diff: str = Field(..., description="Unified diff")
    summary: str = Field(..., description="Summary of changes")
    is_mock: bool = Field(default=False, description="True if generated by mock model")
    generation_timestamp: float = Field(default_factory=time.time)


class VerificationResult(BaseModel):
    """Outcome of patch verification testing."""
    verified: bool = Field(default=False, description="True if all verification tests passed")
    syntax_valid: bool = Field(default=False)
    tests_passed: List[str] = Field(default_factory=list)
    tests_failed: List[str] = Field(default_factory=list)
    command: str = Field(default="")
    exit_code: int = Field(default=1)
    stdout: str = Field(default="")
    stderr: str = Field(default="")
    duration_seconds: float = Field(default=0.0)
    status_label: str = Field(default="UNVERIFIED", description="VERIFIED, VALIDATION_FAILED, etc.")


class ExecutionContext(BaseModel):
    """Central mutable state container for a repair run."""
    task_id: str = Field(default_factory=lambda: f"rf-{uuid.uuid4().hex[:8]}")
    repo_path: Path
    model_name: str = "mock-repair-model"
    is_mock: bool = True
    current_state: AgentState = AgentState.INITIALIZED
    state_history: List[StateTransitionRecord] = Field(default_factory=list)

    bug_report: Optional[BugReport] = None
    repo_summary: Optional[RepoSummary] = None
    reproduction_result: Optional[ReproductionResult] = None
    root_cause_analysis: Optional[RootCauseRecord] = None
    patch: Optional[PatchRecord] = None
    verification_result: Optional[VerificationResult] = None
    human_approved: Optional[bool] = None

    retry_count: int = 0
    max_retries: int = 3
    start_time: float = Field(default_factory=time.time)
    end_time: Optional[float] = None
    failure_reason: Optional[str] = None

    class Config:
        arbitrary_types_allowed = True

